//! Save/profile envelope only (E-047). The returned payload is opaque; its format is still T-016.

use std::io::{Error, ErrorKind, Result};

/// Verify SHA-1 and decompress the complete LZO1X stream. The caller supplies an allocation limit.
/// This does not interpret WSG/profile contents or write any user data.
pub fn decode_envelope(bytes: &[u8], max_output: usize) -> Result<Vec<u8>> {
    let bad = |message| Error::new(ErrorKind::InvalidData, message);
    if bytes.len() < 24 { return Err(bad("save envelope truncated")); }
    if sha1(&bytes[20..]) != bytes[..20] { return Err(bad("save SHA-1 mismatch")); }
    // orig: E-047, size is big-endian for both .sav and profile.bin.
    let size = u32::from_be_bytes(bytes[20..24].try_into().unwrap()) as usize;
    if size > max_output { return Err(bad("save exceeds decompression limit")); }
    let (payload, consumed) = crate::lzo::decompress(&bytes[24..], size)?;
    if consumed != bytes.len() - 24 { return Err(bad("save has trailing compressed data")); }
    Ok(payload)
}

// Format checksum, not authentication. No new dependency is needed for this single digest.
fn sha1(bytes: &[u8]) -> [u8; 20] {
    let mut h = [0x67452301u32, 0xefcdab89, 0x98badcfe, 0x10325476, 0xc3d2e1f0];
    let compress = |block: &[u8], h: &mut [u32; 5]| {
        let mut w = [0u32; 80];
        for (word, chunk) in w.iter_mut().zip(block.as_chunks::<4>().0) { *word = u32::from_be_bytes(*chunk); }
        for i in 16..80 { w[i] = (w[i - 3] ^ w[i - 8] ^ w[i - 14] ^ w[i - 16]).rotate_left(1); }
        let [mut a, mut b, mut c, mut d, mut e] = *h;
        for (i, word) in w.into_iter().enumerate() {
            let (f, k) = match i {
                0..20 => ((b & c) | (!b & d), 0x5a827999),
                20..40 => (b ^ c ^ d, 0x6ed9eba1),
                40..60 => ((b & c) | (b & d) | (c & d), 0x8f1bbcdc),
                _ => (b ^ c ^ d, 0xca62c1d6),
            };
            let next = a.rotate_left(5).wrapping_add(f).wrapping_add(e).wrapping_add(k).wrapping_add(word);
            (a, b, c, d, e) = (next, a, b.rotate_left(30), c, d);
        }
        for (state, value) in h.iter_mut().zip([a, b, c, d, e]) { *state = state.wrapping_add(value); }
    };
    let (blocks, remainder) = bytes.as_chunks::<64>();
    for block in blocks { compress(block, &mut h); }
    let mut tail = [0u8; 128];
    tail[..remainder.len()].copy_from_slice(remainder);
    tail[remainder.len()] = 0x80;
    let end = if remainder.len() < 56 { 64 } else { 128 };
    tail[end - 8..end].copy_from_slice(&(bytes.len() as u64 * 8).to_be_bytes());
    for block in tail[..end].as_chunks::<64>().0 { compress(block, &mut h); }
    let mut digest = [0u8; 20];
    for (chunk, word) in digest.as_chunks_mut::<4>().0.iter_mut().zip(h) { *chunk = word.to_be_bytes(); }
    digest
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn sha1_vectors() {
        let hex = |bytes: &[u8]| sha1(bytes).iter().map(|b| format!("{b:02x}")).collect::<String>();
        assert_eq!(hex(b""), "da39a3ee5e6b4b0d3255bfef95601890afd80709");
        assert_eq!(hex(b"abc"), "a9993e364706816aba3e25717850c26c9cd0d89d");
        assert_eq!(hex(b"abcdbcdecdefdefgefghfghighijhijkijkljklmklmnlmnomnopnopq"), "84983e441c3bd26ebaae4aa1f95129e5e54670f1");
        assert_eq!(hex(&vec![b'a'; 1_000_000]), "34aa973cd4c4daa4f61eeb2bdbad27316534016f");
    }

    fn resign(bytes: &mut [u8]) { let digest = sha1(&bytes[20..]); bytes[..20].copy_from_slice(&digest); }

    #[test]
    fn envelope_rejects_corruption_and_trailing_data() {
        let mut bytes = vec![0u8; 20];
        bytes.extend_from_slice(&[0, 0, 0, 3, 20, b'a', b'b', b'c', 17, 0, 0]);
        resign(&mut bytes);
        // Independently generated by Node crypto.createHash("sha1") for this synthetic stream.
        assert_eq!(bytes[..20], [0x89, 0x5c, 0xb1, 0x10, 0x0e, 0x09, 0x45, 0xd6, 0x52, 0x1f, 0x38, 0xa4, 0xfc, 0xf3, 0xfa, 0x38, 0xdd, 0x0c, 0x79, 0x9b]);
        assert_eq!(decode_envelope(&bytes, 3).unwrap(), b"abc");
        assert!(decode_envelope(&bytes, 2).unwrap_err().to_string().contains("limit"));
        for end in 0..bytes.len() { assert!(decode_envelope(&bytes[..end], 3).is_err()); }
        bytes[25] ^= 1;
        assert!(decode_envelope(&bytes, 3).unwrap_err().to_string().contains("SHA-1"));
        bytes[25] ^= 1;
        bytes.push(0);
        resign(&mut bytes);
        assert!(decode_envelope(&bytes, 3).unwrap_err().to_string().contains("trailing"));
        bytes.pop();
        bytes[23] = 4;
        resign(&mut bytes);
        assert!(decode_envelope(&bytes, 4).is_err());
    }
}
